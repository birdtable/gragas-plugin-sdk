func newPlugin(t *testing.T, file string) *declarative.Plugin {
	t.Helper()
	p, err := declarative.New(read(t, file))
	if err != nil {
		t.Fatal(err)
	}
	return p
}

func presetEntry(key string, target wire.Target, sev wire.Severity, rule string) wire.PresetEntry {
	return wire.PresetEntry{Key: key, Target: target, Severity: sev, Rules: []string{rule}}
}

// TestAPresetIsWrittenFromTheEntriesWithTheRequestsMarkInItsFirstLine: the plain adapter writes one file, the entries
// in the order of their keys, the mark the engine asked for in place of gragas's own in the first line, and a note for
// the entry of a target the tool does not cover.
// Risk: a preset file lacks the mark and the engine refuses the answer, or an entry is written that the tool cannot read.
func TestAPresetIsWrittenFromTheEntriesWithTheRequestsMarkInItsFirstLine(t *testing.T) {
	t.Parallel()
	p := newPlugin(t, "testdata/bridge/plain.yaml")
	resp, err := p.Preset(wire.PresetRequest{ToolVersion: "2.3.0", Mark: "gragas:preset", Inputs: []wire.File{}, Entries: []wire.PresetEntry{
		presetEntry("no-eval", "source", "error", "go.a.1"),
		{Key: "max-len", Target: "source", Severity: "warning", Value: json.RawMessage(`300`), Rules: []string{"go.b.1"}},
		{Key: "trialrule", Target: "config", Severity: "error", Trial: true, Rules: []string{"go.c.1"}},
		presetEntry("other", "prose", "error", "go.d.1"),
	}})
	if err != nil {
		t.Fatal(err)
	}
	const want = "# gragas:preset\nversion: \"2\"\nruleDirs:\n  - rules\nrules:\n  - max-len\n  - no-eval\n  - trialrule\n"
	if len(resp.Files) != 1 || resp.Files[0].Path != "lint-a.yml" || resp.Files[0].Text != want {
		t.Errorf("files = %+v, want one file lint-a.yml with\n%s", resp.Files, want)
	}
	if len(resp.Notes) != 1 || resp.Notes[0] != "go.d.1: lint-a prose other is not shipped: the tool does not cover that target" {
		t.Errorf("notes = %q", resp.Notes)
	}
}

