// TestADeclarativePluginServesAPresetThroughServe: a request on Serve's wire gives a sorted ok answer, the other
// operations answer unsupported, and a bad entry is refused at its pointer.
func TestADeclarativePluginServesAPresetThroughServe(t *testing.T) {
	t.Parallel()
	p := newPlugin(t, "testdata/bridge/plain.yaml")
	call := func(op, body string) string {
		var out bytes.Buffer
		if code := plugin.ServeIO(strings.NewReader(`{"contract":1,"features":[],"op":"`+op+`","body":`+body+`}`), &out, p); code != 0 {
			t.Fatalf("exit %d", code)
		}
		return out.String()
	}
	got := call("preset", `{"tool_version":"2.3.0","mark":"gragas:preset","inputs":[],"entries":[{"key":"b","target":"source","trial":false,"rules":["r"]},{"key":"a","target":"source","trial":false,"rules":["r"]}]}`)
	if want := `{"ok":{"files":[{"path":"lint-a.yml","text":"# gragas:preset\nversion: \"2\"\nruleDirs:\n  - rules\nrules:\n  - a\n  - b\n"}]}}` + "\n"; got != want {
		t.Errorf("preset = %s, want %s", got, want)
	}
	if got := call("rank", `{"tool_version":"2.3.0","pairs":[{"key":"k","aspect":"value","preset":1,"found":2}]}`); !strings.Contains(got, `"unknown"`) {
		t.Errorf("rank = %s, want the word unknown", got)
	}
	if got := call("preset", `{"tool_version":"2.3.0","mark":"m","inputs":[],"entries":[{"key":"a","target":"source","trial":false,"rules":["r"],"options":[1]}]}`); !strings.Contains(got, `"refused"`) || !strings.Contains(got, `/entries/0/options`) {
		t.Errorf("a list of options = %s, want refused at /entries/0/options", got)
	}
}

// TestTheRequestsOwnMarkIsTheFirstLineOfEveryFileOnEveryWritePath: whatever words the engine's mark has, they are the
// first line of every file, in the tool's comment syntax, and gragas's own mark is nowhere in it: on the plain
// path, on the copy-once path (an adapter with no extends) and on the settings-input path. The mark is a parameter of the
// moved writer, and not a replace in its output, which would break silently when the words changed.
// Risk: a preset file whose first line lacks the engine's mark is refused by the engine and by the SDK.
func TestTheRequestsOwnMarkIsTheFirstLineOfEveryFileOnEveryWritePath(t *testing.T) {
	t.Parallel()
	plain := string(read(t, "testdata/bridge/plain.yaml"))
	settings := read(t, "testdata/clean.yaml")
	copyOnce := strings.Replace(plain, "extends: true", "extends: false", 1)
	if copyOnce == plain {
		t.Fatal("the fixture does not say extends: true")
	}
	entries := []wire.PresetEntry{presetEntry("a", "source", "error", "go.a.1")}
	const mark = "managed-by: gragas 0 (no. 7), edit never"
	for name, c := range map[string]struct {
		adapter []byte
		inputs  []wire.File
	}{
		"plain":            {[]byte(plain), []wire.File{}},
		"copy once":        {[]byte(copyOnce), []wire.File{}},
		"a settings input": {settings, []wire.File{{Path: "settings.yml", Data: wire.Bytes{Data: []byte("enable:\n  # lint:begin\n  # lint:end\n")}}}},
	} {
		p, err := declarative.New(c.adapter)
		if err != nil {
			t.Fatalf("%s: %v", name, err)
		}
		resp, err := p.Preset(wire.PresetRequest{ToolVersion: "2.3.0", Mark: mark, Inputs: c.inputs, Entries: entries})
		if err != nil || len(resp.Files) == 0 {
			t.Fatalf("%s: %v", name, err)
		}
		for _, f := range resp.Files {
			first, _, _ := strings.Cut(f.Text, "\n")
			if first != "# "+mark || strings.Contains(f.Text, "gragas from the rulebook") {
				t.Errorf("%s: %s begins %q, want %q and none of gragas's own mark", name, f.Path, first, "# "+mark)
			}
		}
	}
}

// withVariant is the clean adapter with one passage of its text replaced, as a plugin.
func withVariant(t *testing.T, old, new string) *declarative.Plugin {
	t.Helper()
	text := string(read(t, "testdata/clean.yaml"))
	if !strings.Contains(text, old) {
		t.Fatalf("the clean adapter has no %q", old)
	}
	p, err := declarative.New([]byte(strings.Replace(text, old, new, 1)))
	if err != nil {
		t.Fatal(err)
	}
	return p
}

func runResult(exit int, stdout string, files ...wire.File) wire.Result {
	cut := false
	return wire.Result{Round: 0, Step: 0, Kind: wire.KindRun, Exit: &exit, Stdout: &wire.Bytes{Data: []byte(stdout)}, Stderr: &wire.Bytes{}, Cut: &cut, Files: append([]wire.File{}, files...)}
}

