// TestAMarkThatCouldBreakOutOfItsCommentIsRefusedAtMark: the engine sets the mark today, but the writer does not trust its
// shape: a control character (a CR, which YAML reads as a line break, or any other) refuses the request at /mark, and so does
// the closer */ where the adapter's comment is a block, since it would end the comment early. A mark that holds */ is no
// trouble in a hash comment, and goes through.
// Risk: a mark of a shape the engine does not send turns the rest of the mark's line into a line of the config.
func TestAMarkThatCouldBreakOutOfItsCommentIsRefusedAtMark(t *testing.T) {
	t.Parallel()
	hash := newPlugin(t, "testdata/bridge/plain.yaml")
	blockText := strings.Replace(string(read(t, "testdata/bridge/plain.yaml")), "  format: yaml\n  comment: hash", "  format: jsonc\n  comment: block", 1)
	block, err := declarative.New([]byte(blockText))
	if err != nil {
		t.Fatal(err)
	}
	entries := []wire.PresetEntry{presetEntry("a", "source", "error", "go.a.1")}
	try := func(p *declarative.Plugin, mark string) (wire.PresetResponse, error) {
		return p.Preset(wire.PresetRequest{ToolVersion: "2.3.0", Mark: mark, Inputs: []wire.File{}, Entries: entries})
	}
	for name, c := range map[string]struct {
		p    *declarative.Plugin
		mark string
	}{
		"a CR":                 {hash, "ok\rkey: x"},
		"a tab-less control":   {hash, "ok\x01x"},
		"a DEL":                {hash, "ok\x7fx"},
		"U+0085":               {hash, "ok\u0085x"},
		"U+2028":               {hash, "ok\u2028x"},
		"U+2029":               {hash, "ok\u2029x"},
		"a closer in a block":  {block, "ok */ x"},
		"a control in a block": {block, "ok\rx"},
	} {
		_, err := try(c.p, c.mark)
		if we, ok := err.(*wire.Error); !ok || we.Code != wire.CodeRefused || we.Path != "/mark" {
			t.Errorf("%s: %v, want refused at /mark", name, err)
		}
	}
	if got, err := try(hash, "ok */ x"); err != nil || !strings.HasPrefix(got.Files[0].Text, "# ok */ x\n") {
		t.Errorf("a closer in a hash comment: %v", err)
	}
	if got, err := try(block, "ok * / x"); err != nil || !strings.HasPrefix(got.Files[0].Text, "/* ok * / x */\n") {
		t.Errorf("a star and a slash apart in a block: %v", err)
	}
}

