// TestAFailedRunIsRanFalseAndNeverAnEmptyList: an exit code that is none of the ran codes (0 only, where the adapter names
// none), the output cut, and a finding of an error key of the adapter's each answer ran: false with why and no findings;
// the adapter's own ran codes are ran.
// Risk: a tool that failed is read as a tool that found nothing.
func TestAFailedRunIsRanFalseAndNeverAnEmptyList(t *testing.T) {
	t.Parallel()
	p := newPlugin(t, "testdata/clean.yaml")
	got, err := findingsOf(t, p, "", runResult(2, "", outFile(printedIssues)))
	if err != nil || got.Ran || got.Why == "" || len(got.Findings) != 0 {
		t.Errorf("exit 2: %+v, %v", got, err)
	}
	if got, err := findingsOf(t, p, "", runResult(1, "", outFile(printedIssues))); err != nil || got.Ran {
		t.Errorf("exit 1 with no ran codes: %+v, %v", got, err)
	}
	codes := withVariant(t, "  output:\n    format: json\n", "  output:\n    format: json\n    ran_codes: [0, 1]\n")
	if got, err := findingsOf(t, codes, "", runResult(1, "", outFile(printedIssues))); err != nil || !got.Ran || len(got.Findings) != 2 {
		t.Errorf("exit 1 as a ran code: %+v, %v", got, err)
	}
	if got, err := findingsOf(t, codes, "", runResult(2, "", outFile(printedIssues))); err != nil || got.Ran {
		t.Errorf("exit 2 beside ran codes: %+v, %v", got, err)
	}
	yes := true
	cutRun := runResult(0, "", outFile(printedIssues))
	cutRun.Cut = &yes
	if got, err := findingsOf(t, p, "", cutRun); err != nil || got.Ran || !strings.Contains(got.Why, "cut") {
		t.Errorf("a cut run: %+v, %v", got, err)
	}
	keys := withVariant(t, "  output:\n    format: json\n", "  output:\n    format: json\n    error_keys: [no-eval]\n")
	if got, err := findingsOf(t, keys, "", runResult(0, "", outFile(printedIssues))); err != nil || got.Ran || len(got.Findings) != 0 || !strings.Contains(got.Why, "no-eval") {
		t.Errorf("an error key: %+v, %v", got, err)
	}
	if _, err := findingsOf(t, p, ""); err == nil {
		t.Error("no run in have was answered")
	}
}

