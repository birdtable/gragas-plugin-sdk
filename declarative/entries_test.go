// TestAnAdapterWithASettingsInputIsWrittenFromThatInput: the list is spliced between the input's two marker lines, each
// entry with its rule; a request without the input, or with content between the markers, is refused at its pointer.
func TestAnAdapterWithASettingsInputIsWrittenFromThatInput(t *testing.T) {
	t.Parallel()
	p := newPlugin(t, "testdata/clean.yaml")
	entries := []wire.PresetEntry{presetEntry("no-eval", "source", "error", "go.a.1"), {Key: "max-len", Target: "source", Severity: "warning", Value: json.RawMessage(`300`), Rules: []string{"go.b.1"}}}
	in := func(text string) []wire.File {
		return []wire.File{{Path: "settings.yml", Data: wire.Bytes{Data: []byte(text)}}}
	}
	resp, err := p.Preset(wire.PresetRequest{ToolVersion: "2.3.0", Mark: "gragas:preset", Entries: entries, Inputs: in("base: 1\nenable:\n  # lint:begin\n  # lint:end\nmore: 2\n")})
	const want = "# gragas:preset\nbase: 1\nenable:\n  # lint:begin\n  - max-len # go.b.1\n  - no-eval # go.a.1\n  # lint:end\nmore: 2\n"
	if err != nil || len(resp.Files) != 1 || resp.Files[0].Path != "lint-a.yml" || resp.Files[0].Text != want {
		t.Errorf("files = %+v, err %v, want\n%s", resp.Files, err, want)
	}
	for name, c := range map[string]struct {
		inputs []wire.File
		path   string
	}{
		"no input":                 {[]wire.File{}, "/inputs"},
		"an input of another path": {[]wire.File{{Path: "other.yml", Data: wire.Bytes{Data: []byte("x")}}}, "/inputs"},
		"content between markers":  {in("enable:\n  # lint:begin\n  - old\n  # lint:end\n"), "/inputs/0"},
		"no markers":               {in("enable:\n"), "/inputs/0"},
	} {
		_, err := p.Preset(wire.PresetRequest{ToolVersion: "2.3.0", Entries: entries, Inputs: c.inputs})
		we, ok := err.(*wire.Error)
		if !ok || we.Code != wire.CodeRefused || we.Path != c.path {
			t.Errorf("%s: %v, want refused at %s", name, err, c.path)
		}
	}
}

