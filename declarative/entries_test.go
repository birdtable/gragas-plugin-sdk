	yes := true
	cutRun.Cut = &yes
	_, err = entriesOf(t, p, cutRun)
	unreadableAt(t, "a cut run", err, "/have/0/stdout")
	_, err = entriesOf(t, p, runResult(0, `{"rules":`))
